# DATA LOADING
# --------------------------------------------------

DATA_FILE = (
    Path(__file__).resolve().parent
    / "outputs"
    / "risk_scored_vulnerabilities.csv"
)


@st.cache_data
def load_data(file_path, modified_time):
    data = pd.read_csv(file_path)

    required_columns = [
        "cveID",
        "vendorProject",
        "product",
        "risk_score",
        "risk_tier",
        "ransomware",
    ]

    missing_columns = [
        column
        for column in required_columns
        if column not in data.columns
    ]

    if missing_columns:
        raise ValueError(
            f"Missing required columns: {', '.join(missing_columns)}"
        )

    data["risk_score"] = pd.to_numeric(
        data["risk_score"], errors="coerce"
    )

    data["ransomware"] = pd.to_numeric(
        data["ransomware"], errors="coerce"
    )

    data["risk_tier"] = data["risk_tier"].fillna("Unknown")

    return data


st.markdown(
    '<p class="main-title">🛡️ CyberIntel</p>',
    unsafe_allow_html=True,
)

st.markdown(
    '<p class="subtitle">'
    "Cybersecurity Threat Intelligence Dashboard"
    "</p>",
    unsafe_allow_html=True,
)

st.write(
    "Analyze known vulnerabilities, explore estimated risk levels, "
    "identify ransomware-related vulnerabilities, and search security data."
)

if not DATA_FILE.exists():
    st.error(
        "Risk data not found. Make sure this file exists: "
        "outputs/risk_scored_vulnerabilities.csv"
    )
    st.stop()

try:
    df = load_data(
        str(DATA_FILE),
        DATA_FILE.stat().st_mtime,
    )
except (ValueError, OSError, pd.errors.ParserError) as error:
    st.error(f"Unable to load vulnerability data: {error}")
    st.stop()

if df.empty:
    st.warning("The vulnerability dataset is empty.")
    st.stop()

# --------------------------------------------------
# SIDEBAR
# --------------------------------------------------

